export function getToolsByCategory(categoryId: string): AITool[] {
  if (categoryId === 'all') return aiTools;
  return aiTools.filter(tool => tool.category === categoryId);
}

export function getFeaturedTools(): AITool[] {
  return aiTools.filter(tool => tool.featured);
}

export function getNewTools(): AITool[] {
  return aiTools.filter(tool => tool.new);
}

export function searchTools(query: string): AITool[] {
  const q = query.toLowerCase();
  return aiTools.filter(tool =>
    tool.name.toLowerCase().includes(q) ||
    tool.nameCn.includes(query) ||
    tool.nameJp.includes(query) ||
    tool.nameKr.includes(query) ||
    tool.description.toLowerCase().includes(q) ||
    tool.descriptionCn.includes(query) ||
    tool.descriptionJp.includes(query) ||
    tool.descriptionKr.includes(query) ||
    tool.tags.some(tag => tag.toLowerCase().includes(q)) ||
    tool.tagsCn.some(tag => tag.includes(query)) ||
    tool.tagsJp.some(tag => tag.includes(query)) ||
    tool.tagsKr.some(tag => tag.includes(query))
  );
}
